@lru_cache(maxsize=64)
def _icon_source(name: str) -> str:
    path = ICONS / f"{name}.svg"
    if not path.exists():
        raise KeyError(f"no Lucide icon {name!r} in {ICONS} (add it to scripts/fetch_icons.py)")
    return " ".join(path.read_text(encoding="utf-8").split())


def icon(name: str, size: int = 18, color: str = "currentColor", stroke: float = 2.0) -> str:
    """A Lucide icon as inline SVG (inherits the text colour unless `color` is given)."""
    svg = _icon_source(name)
    svg = re.sub(r'width="\d+"', f'width="{size}"', svg, count=1)
    svg = re.sub(r'height="\d+"', f'height="{size}"', svg, count=1)
    svg = svg.replace('stroke="currentColor"', f'stroke="{html.escape(color)}"', 1)
    svg = re.sub(r'stroke-width="[\d.]+"', f'stroke-width="{stroke:g}"', svg, count=1)
    return svg.replace("<svg ", '<svg class="lc" aria-hidden="true" ', 1)


def data_uri(path: Path) -> str:
    mime = "image/svg+xml" if path.suffix == ".svg" else f"image/{path.suffix.lstrip('.')}"
    return f"data:{mime};base64,{base64.b64encode(path.read_bytes()).decode()}"


def illustration(name: str, width: int = 260, alt: str = "") -> str:
    """A self-made illustration (assets/brand/<name>.svg) as an <img> tag."""
    return (f'<img src="{data_uri(BRAND / f"{name}.svg")}" width="{width}" '
            f'alt="{html.escape(alt or name)}" style="max-width:100%">')  # fmt: skip


