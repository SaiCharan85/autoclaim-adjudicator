# ---------------------------------------------------------------- demo photos (Pexels/Unsplash API)


def demo_photos(folder: Path = DEMO) -> list[dict[str, Any]]:
    """Photos fetched by scripts/fetch_demo_images.py with their credit (photographer, links)."""
    meta = folder / "credits.json"
    if not meta.exists():
        return []
    rows: list[dict[str, Any]] = json.loads(meta.read_text(encoding="utf-8"))
    return [r for r in rows if r.get("url") or (r.get("file") and (folder / r["file"]).exists())]


def photo_src(photo: dict[str, Any], folder: Path = DEMO) -> str:
    """Hotlinked URL (Unsplash requires it) or the downloaded file inlined (Pexels)."""
    return str(photo["url"]) if photo.get("url") else data_uri(folder / str(photo["file"]))


def photo_for(key: int | str, photos: list[dict[str, Any]]) -> dict[str, Any] | None:
    """A stable photo per story (same story, same photo)."""
    if not photos:
        return None
    n = sum(map(ord, str(key))) if not isinstance(key, int) else key
    return photos[n % len(photos)]


def credit_html(photo: dict[str, Any]) -> str:
    """The provider's attribution line: 'Photo by <name> on <Pexels|Unsplash>', both linked."""
    who = html.escape(photo["photographer"])
    who_url, src_url = html.escape(photo["photographer_url"]), html.escape(photo["source_url"])
    where = html.escape(photo["provider"])
    return (f'Photo by <a href="{who_url}" target="_blank">{who}</a> on '
            f'<a href="{src_url}" target="_blank">{where}</a>')  # fmt: skip
