"""Quick tabular profile: class balance, missingness, cardinality, and univariate target rates.

Outputs aggregate statistics only (no raw rows), so the rendered report is safe to commit.
"""

import argparse
from collections.abc import Sequence
from pathlib import Path

import pandas as pd

from autoclaim.datasets.schema import TableSchema, ValidationReport, validate


def class_balance(df: pd.DataFrame, target: str) -> pd.DataFrame:
    counts = df[target].value_counts().sort_index()
    return pd.DataFrame({"count": counts, "share": (counts / len(df)).round(4)})


def missingness(df: pd.DataFrame, report: ValidationReport) -> pd.DataFrame:
    """Nulls plus schema-declared sentinels (e.g. Age == 0) per column; only non-zero rows."""
    nulls = df.isna().sum()
    sentinels = pd.Series(
        {w.column: w.n_rows for w in report.warnings if w.check == "sentinel"}, dtype="int64"
    )
    out = pd.DataFrame({"nulls": nulls}).join(sentinels.rename("sentinels")).fillna(0).astype(int)
    out["share"] = ((out["nulls"] + out["sentinels"]) / len(df)).round(4)
    return out[(out["nulls"] > 0) | (out["sentinels"] > 0)].sort_values("share", ascending=False)


def cardinality(df: pd.DataFrame) -> pd.DataFrame:
    nunique = df.nunique(dropna=False)
    top_share = df.apply(lambda s: s.value_counts(normalize=True, dropna=False).iloc[0])
    top_value = df.apply(lambda s: s.value_counts(dropna=False).index[0])
    out = pd.DataFrame(
        {"nunique": nunique, "top_value": top_value.astype(str), "top_share": top_share.round(4)}
    )
    out["note"] = ""
    out.loc[out["nunique"] == len(df), "note"] = "unique (ID-like)"
    out.loc[out["nunique"] == 1, "note"] = "constant"
    out.loc[(out["top_share"] >= 0.95) & (out["nunique"] > 1), "note"] = "near-constant"
    return out.sort_values("nunique")


def target_rate_by(df: pd.DataFrame, target: str, column: str, min_count: int = 30) -> pd.DataFrame:
    """Target rate per category of `column`, for categories with at least `min_count` rows."""
    grouped = df.groupby(column, observed=True)[target].agg(["count", "mean"])
    grouped = grouped[grouped["count"] >= min_count].rename(columns={"mean": "rate"})
    grouped["rate"] = grouped["rate"].round(4)
    return grouped.sort_values("rate", ascending=False)


def target_rate_spread(
    df: pd.DataFrame, target: str, max_cardinality: int = 30, min_count: int = 30
) -> pd.DataFrame:
    """Min/max category target rate per low-cardinality column: a quick univariate signal scan."""
    rows = []
    for col in df.columns:
        if col == target or df[col].nunique() > max_cardinality:
            continue
        rates = target_rate_by(df, target, col, min_count)["rate"]
        if len(rates) < 2:
            continue
        rows.append(
            {
                "column": col,
                "min_rate": rates.min(),
                "max_rate": rates.max(),
                "spread": round(rates.max() - rates.min(), 4),
                "highest_category": str(rates.idxmax()),
            }
        )
    if not rows:
        return pd.DataFrame(columns=["min_rate", "max_rate", "spread", "highest_category"])
    return pd.DataFrame(rows).set_index("column").sort_values("spread", ascending=False)


def to_markdown(df: pd.DataFrame, index_name: str | None = None) -> str:
    """Minimal GitHub-markdown table (avoids a tabulate dependency)."""
    header = [index_name or str(df.index.name or "")] + [str(c) for c in df.columns]
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    # itertuples keeps per-column dtypes (iterrows would upcast int counts to float)
    for row in df.itertuples(name=None):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def render_report(df: pd.DataFrame, schema: TableSchema, time_column: str | None = None) -> str:
    report = validate(df, schema)
    t = schema.target
    parts = [
        f"# Data profile: `{schema.name}`",
        "",
        "_Auto-generated by `scripts/profile_data.py`. Aggregates only; no raw rows._",
        "",
        f"**Rows:** {len(df):,}  **Columns:** {df.shape[1]}  "
        f"**Schema errors:** {len(report.errors)}  **Warnings:** {len(report.warnings)}",
        "",
        "## Class balance",
        to_markdown(class_balance(df, t), t),
    ]
    if time_column:
        parts += [
            "",
            f"## Target rate by `{time_column}`",
            to_markdown(target_rate_by(df, t, time_column, 1)),
        ]
    issues = report.errors + report.warnings
    if issues:
        table = pd.DataFrame(
            [
                {
                    "column": i.column,
                    "check": i.check,
                    "rows": i.n_rows,
                    "examples": ", ".join(i.examples),
                }
                for i in issues
            ]
        ).set_index("column")
        parts += ["", "## Schema findings", to_markdown(table)]
    parts += [
        "",
        "## Missing / sentinel values",
        to_markdown(missingness(df, report), "column"),
        "",
        "## Cardinality",
        to_markdown(cardinality(df), "column"),
        "",
        "## Univariate target-rate spread (categories with >= 30 rows)",
        to_markdown(target_rate_spread(df, t)),
        "",
    ]
    return "\n".join(parts)


def main(argv: Sequence[str] | None = None) -> int:
    from autoclaim.datasets import vehicle_fraud

    parser = argparse.ArgumentParser(
        description="Profile the fraud table and write a markdown report."
    )
    parser.add_argument(
        "--csv", type=Path, default=None, help="defaults to data/raw/vehicle_fraud/"
    )
    parser.add_argument("--out", type=Path, default=Path("docs/data_profile.md"))
    args = parser.parse_args(argv)

    df, report = vehicle_fraud.load_validated(args.csv)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        render_report(df, vehicle_fraud.SCHEMA, time_column="Year"), encoding="utf-8"
    )
    print(f"{len(df):,} rows, {len(report.warnings)} schema warnings -> {args.out}")
    return 0
